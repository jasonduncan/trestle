//! The auto-apply classifier (design §7.1). One function decides whether a
//! pending migration may be applied without a human: [`classify`].
//!
//! A migration is `auto` only if it is atomic, has no data step, its SQL is
//! exactly what the planner renders from its operations, and every
//! operation is on the allowlist below. Everything else needs approval,
//! with reason codes saying why.

use std::collections::BTreeSet;

use serde::Serialize;

use crate::schema::{DbDefault, SchemaState, StateOp};
use crate::{Migration, MigrationSet, sql};

/// Why a migration needs approval. Stable strings in `trestle.plan/1`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Reason {
    /// Drops or renames something the running version may still use.
    Destructive,
    /// `"atomic": false`.
    NonAtomic,
    /// Runs a data step or backfills rows.
    DataStep,
    /// The SQL is not what the planner renders from the operations, or
    /// there are no operations to check it against.
    HandSql,
    /// May rewrite or scan the whole table (volatile default, NOT NULL).
    RewriteRisk,
    /// Locks or scans an existing table (new index, unique, FK or check).
    ExistingTableLock,
}

impl Reason {
    pub fn as_str(self) -> &'static str {
        match self {
            Reason::Destructive => "destructive",
            Reason::NonAtomic => "non_atomic",
            Reason::DataStep => "data_step",
            Reason::HandSql => "hand_sql",
            Reason::RewriteRisk => "rewrite_risk",
            Reason::ExistingTableLock => "existing_table_lock",
        }
    }
}

/// The SQL `makemigrations` writes for these operations.
pub fn generated_sql(app: &str, id: &str, before: &SchemaState, ops: &[StateOp]) -> Option<String> {
    let rendered = sql::render(before, ops).ok()?;
    Some(format!(
        "-- {app}.{id}: generated by makemigrations. Review before committing.\n{rendered}\n"
    ))
}

/// Reasons one operation needs approval; empty means allowlisted.
/// `created` holds models created earlier in the same migration.
pub fn op_reasons(op: &StateOp, created: &BTreeSet<String>) -> Vec<Reason> {
    let new_table = created.contains(op.model());
    match op {
        StateOp::CreateModel { .. } => vec![],
        StateOp::AddField { field, .. } => {
            if new_table {
                return vec![];
            }
            let mut reasons = Vec::new();
            if field.references.is_some() || field.check.is_some() || field.primary_key {
                reasons.push(Reason::ExistingTableLock);
            }
            let constant_default = matches!(
                field.default,
                Some(DbDefault::Int { .. } | DbDefault::Text { .. } | DbDefault::Bool { .. })
            );
            if matches!(field.default, Some(DbDefault::Now))
                || (!field.nullable && !constant_default)
            {
                reasons.push(Reason::RewriteRisk);
            }
            reasons
        }
        StateOp::AddIndex { .. } | StateOp::AddUnique { .. } | StateOp::AlterCheck { .. } => {
            if new_table {
                vec![]
            } else {
                vec![Reason::ExistingTableLock]
            }
        }
        StateOp::AlterNullability { .. } => vec![Reason::RewriteRisk],
        StateOp::Backfill { .. } => vec![Reason::DataStep],
        StateOp::RemoveModel { .. }
        | StateOp::RemoveField { .. }
        | StateOp::RemoveUnique { .. }
        | StateOp::RemoveIndex { .. }
        | StateOp::RenameTable { .. }
        | StateOp::RenameColumn { .. } => vec![Reason::Destructive],
    }
}

/// Reasons `migration` needs approval, sorted and unique; empty = `auto`.
/// `before` is the historical state just before it, when known.
pub fn classify(
    migration: &Migration,
    ops: Option<&[StateOp]>,
    before: Option<&SchemaState>,
) -> Vec<Reason> {
    let mut reasons = BTreeSet::new();
    if !migration.options().atomic {
        reasons.insert(Reason::NonAtomic);
    }
    if migration.data.is_some() {
        reasons.insert(Reason::DataStep);
    }
    match (ops, before) {
        (Some(ops), Some(before)) => {
            let mut created = BTreeSet::new();
            for op in ops {
                reasons.extend(op_reasons(op, &created));
                if let StateOp::CreateModel { model } = op {
                    created.insert(model.id.clone());
                }
            }
            let expected = generated_sql(migration.app, migration.id, before, ops);
            // A data-only migration's SQL is a comment; nothing to compare.
            let data_only =
                ops.is_empty() && migration.data.is_some() && sql_is_comment(migration.sql);
            if expected.as_deref() != Some(migration.sql) && !data_only {
                reasons.insert(Reason::HandSql);
            }
        }
        _ => {
            reasons.insert(Reason::HandSql);
        }
    }
    reasons.into_iter().collect()
}

fn sql_is_comment(sql: &str) -> bool {
    sql.lines()
        .all(|l| l.trim().is_empty() || l.trim_start().starts_with("--"))
}

/// Reasons for every migration in `set`, in order.
pub fn classify_set(set: &MigrationSet) -> Vec<Vec<Reason>> {
    let states = set.states().ok();
    set.iter()
        .enumerate()
        .map(|(i, m)| {
            let ops = set.manifest(m.key()).map(|man| man.operations.as_slice());
            let before = states.as_ref().map(|s| {
                if i == 0 {
                    SchemaState::default()
                } else {
                    s[i - 1].clone()
                }
            });
            classify(m, ops, before.as_ref())
        })
        .collect()
}

/// A human label: `destructive`, `data` or `additive`.
pub fn risk(reasons: &[Reason]) -> &'static str {
    if reasons.contains(&Reason::Destructive) {
        "destructive"
    } else if reasons.contains(&Reason::DataStep) {
        "data"
    } else {
        "additive"
    }
}
