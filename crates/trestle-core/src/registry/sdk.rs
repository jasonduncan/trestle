//! Generated TypeScript client (design doc §11.2).
//!
//! A build artifact, not runtime metadata: one type per contract and one
//! function per managed operation published to an audience. Each function
//! puts path fields in the URL, sends `If-Match` for preconditioned
//! bindings, uses the query string for GET/DELETE and the JSON body
//! otherwise, and returns a discriminated result carrying problem+json.
//! Types describe what the server promises; responses are not re-validated
//! at runtime by this client.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use trestle_protocol::interaction::BodySource;
use trestle_protocol::{Audience, ContractDoc, FieldType};

use super::Registry;

fn type_name(contract_id: &str) -> String {
    contract_id
        .split(['.', '_'])
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            chars
                .next()
                .map(|c| c.to_uppercase().chain(chars).collect::<String>())
                .unwrap_or_default()
        })
        .collect()
}

fn function_name(operation_id: &str) -> String {
    let name = type_name(operation_id);
    let mut chars = name.chars();
    chars
        .next()
        .map(|c| c.to_lowercase().chain(chars).collect())
        .unwrap_or_default()
}

fn ts_type(ty: &FieldType, contracts: &mut BTreeMap<String, ContractDoc>) -> String {
    match ty {
        // Decimals, dates, instants and durations travel as strings
        // (ADR-022), so they stay strings here: no rounding, no parsing.
        FieldType::Text { .. }
        | FieldType::Uuid
        | FieldType::Digits
        | FieldType::Decimal { .. }
        | FieldType::Date
        | FieldType::Instant
        | FieldType::Duration
        | FieldType::Reference { .. } => "string".into(),
        FieldType::Money { .. } => "{ amount: string; currency: string }".into(),
        FieldType::Integer { .. } => "number".into(),
        FieldType::Boolean => "boolean".into(),
        FieldType::Enum { values, .. } => values
            .iter()
            .map(|v| format!("{v:?}"))
            .collect::<Vec<_>>()
            .join(" | "),
        FieldType::Items { item, .. } => {
            contracts
                .entry(item.id.clone())
                .or_insert_with(|| (**item).clone());
            format!("{}[]", type_name(&item.id))
        }
        // A discriminated union TypeScript narrows on the tag (ADR-028).
        FieldType::Union { tag, variants } => variants
            .iter()
            .map(|(variant, doc)| {
                let mut members = vec![format!("{tag}: {variant:?}")];
                members.extend(doc.fields.iter().map(|field| {
                    let mut ty = ts_type(&field.ty, contracts);
                    if field.nullable {
                        ty = format!("{ty} | null");
                    }
                    let optional = if field.required { "" } else { "?" };
                    format!("{}{optional}: {ty}", field.name)
                }));
                format!("{{ {} }}", members.join("; "))
            })
            .collect::<Vec<_>>()
            .join(" | "),
    }
}

fn interface(contract: &ContractDoc, contracts: &mut BTreeMap<String, ContractDoc>) -> String {
    let mut out = format!(
        "/** `{}` {} ({} contract). */\nexport interface {} {{\n",
        contract.id,
        contract.version,
        contract.kind.as_str(),
        type_name(&contract.id)
    );
    for field in &contract.fields {
        let mut ty = ts_type(&field.ty, contracts);
        if field.nullable {
            ty = format!("{ty} | null");
        }
        let optional = if field.required { "" } else { "?" };
        let _ = writeln!(out, "  {}{optional}: {ty};", field.name);
    }
    out.push_str("}\n");
    out
}

const PRELUDE: &str = r#"// Generated by Trestle from the registry. Do not edit; regenerate instead.
/* eslint-disable */

export interface Problem {
  type?: string;
  title?: string;
  status: number;
  code?: string;
  detail?: string;
  request_id?: string;
  errors?: { pointer: string; code: string; message: string; params?: Record<string, unknown> }[];
}

export type Result<T> =
  | { ok: true; status: number; value: T; etag?: string }
  | { ok: false; status: number; problem: Problem };

/** Sends one request. Implementations add credentials and tenant selection. */
export interface Transport {
  send(request: {
    method: string;
    path: string;
    query?: Record<string, string>;
    headers?: Record<string, string>;
    body?: unknown;
  }): Promise<{ status: number; body: unknown; etag?: string }>;
}

type Fields = Record<string, unknown>;

function split(input: Fields, path: string[], precondition?: [string, string]) {
  const rest: Fields = { ...input };
  const params: Record<string, string> = {};
  for (const name of path) {
    params[name] = String(rest[name]);
    delete rest[name];
  }
  const headers: Record<string, string> = {};
  if (precondition) {
    const [field, representation] = precondition;
    headers["If-Match"] = `"${representation}:${String(rest[field])}"`;
    delete rest[field];
  }
  return { rest, params, headers };
}

function fill(template: string, params: Record<string, string>): string {
  return template.replace(/\{([a-z_]+)\}/g, (_, name: string) => encodeURIComponent(params[name] ?? ""));
}

function query(fields: Fields): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [name, value] of Object.entries(fields)) {
    if (value !== undefined && value !== null) out[name] = String(value);
  }
  return out;
}

async function call<T>(
  transport: Transport,
  method: string,
  template: string,
  input: Fields,
  path: string[],
  bodyInQuery: boolean,
  success: number,
  precondition?: [string, string],
): Promise<Result<T>> {
  const { rest, params, headers } = split(input, path, precondition);
  const reply = await transport.send({
    method,
    path: fill(template, params),
    headers,
    ...(bodyInQuery ? { query: query(rest) } : { body: rest }),
  });
  if (reply.status === success) {
    return { ok: true, status: reply.status, value: reply.body as T, etag: reply.etag };
  }
  const problem = (typeof reply.body === "object" && reply.body !== null ? reply.body : {}) as Problem;
  return { ok: false, status: reply.status, problem: { ...problem, status: reply.status } };
}
"#;

impl<S> Registry<S> {
    /// TypeScript client for managed operations published to `audience`.
    pub fn typescript_sdk(&self, audience: Audience) -> String {
        let mut contracts: BTreeMap<String, ContractDoc> = BTreeMap::new();
        let mut functions = String::new();
        for op in self
            .operations
            .iter()
            .filter(|o| o.info.audiences.contains(&audience))
        {
            let Some(binding) = &op.binding else { continue };
            contracts.insert(op.input.id.clone(), (*op.input).clone());
            contracts.insert(op.output.id.clone(), (*op.output).clone());
            let input = type_name(&op.input.id);
            let output = if binding.no_content {
                "void".to_owned()
            } else {
                type_name(&op.output.id)
            };
            let path: Vec<String> = binding
                .path_params()
                .iter()
                .map(|p| format!("{p:?}"))
                .collect();
            let precondition = binding
                .if_match
                .as_ref()
                .map(|field| format!(", [{field:?}, {:?}]", op.output.id))
                .unwrap_or_default();
            let _ = write!(
                functions,
                "\n/** {} (`{}` {}): {} {} */\nexport function {}(transport: Transport, input: {input}): Promise<Result<{output}>> {{\n  return call<{output}>(transport, {:?}, {:?}, input as unknown as Fields, [{}], {}, {}{precondition});\n}}\n",
                op.info.summary,
                op.info.id,
                op.info.version,
                binding.method,
                binding.path,
                function_name(&op.info.id),
                binding.method,
                binding.path,
                path.join(", "),
                binding.body == BodySource::None,
                binding.success_status,
            );
        }
        let mut types = String::new();
        let mut done: Vec<String> = Vec::new();
        // Items may pull in further contracts; loop until stable.
        loop {
            let pending: Vec<ContractDoc> = contracts
                .values()
                .filter(|c| !done.contains(&c.id))
                .cloned()
                .collect();
            if pending.is_empty() {
                break;
            }
            for contract in pending {
                types.push('\n');
                types.push_str(&interface(&contract, &mut contracts));
                done.push(contract.id.clone());
            }
        }
        format!("{PRELUDE}{types}{functions}")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_are_stable_identifiers() {
        assert_eq!(type_name("lessons.create.input"), "LessonsCreateInput");
        assert_eq!(type_name("lessons.view.page"), "LessonsViewPage");
        assert_eq!(function_name("lessons.update"), "lessonsUpdate");
        assert_eq!(function_name("units.list"), "unitsList");
    }

    #[test]
    fn a_union_is_a_discriminated_union_on_its_tag() {
        use trestle_protocol::Field;
        let card = ContractDoc::input("x.card", "1")
            .field(Field::text("last4"))
            .field(Field::money("limit", 8, 2).optional().nullable());
        let cash = ContractDoc::input("x.cash", "1");
        let payment = Field::union("payment", "method", &[("card", &card), ("cash", &cash)]);
        assert_eq!(
            ts_type(&payment.ty, &mut BTreeMap::new()),
            r#"{ method: "card"; last4: string; limit?: { amount: string; currency: string } | null } | { method: "cash" }"#
        );
    }
}
